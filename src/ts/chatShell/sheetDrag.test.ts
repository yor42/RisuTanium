import { describe, expect, it } from 'vitest'
import { createSheetDrag, SHEET_CLOSE_FRACTION, SHEET_FLING_PX_MS, SHEET_REST_LAG_MS, SHEET_SLOP_PX, SHEET_VELOCITY_WINDOW_MS } from './sheetDrag'

describe('sheet drag-down gesture (CHORE-726)', () => {
    it('uses the mockup thresholds', () => {
        expect(SHEET_CLOSE_FRACTION).toBe(0.3)
        expect(SHEET_FLING_PX_MS).toBe(0.5)
        expect(SHEET_SLOP_PX).toBe(4)
    })
    it('follows the finger downward one to one and never above the rest position', () => {
        const drag = createSheetDrag()
        drag.down(100, 0)
        expect(drag.move(102, 10)).toBe(0)
        expect(drag.move(160, 100)).toBe(60)
        expect(drag.move(40, 200)).toBe(0)
    })
    it('closes past 30 % of the height on a slow release and stays below it', () => {
        const past = createSheetDrag()
        past.down(0, 0)
        past.move(100, 1000)
        past.move(130, 2000)
        expect(past.up(130, 2100, 400)).toBe('close')
        const short = createSheetDrag()
        short.down(0, 0)
        short.move(100, 1000)
        short.move(110, 2000)
        expect(short.up(110, 2100, 400)).toBe('stay')
    })
    it('closes on a downward fling faster than 0.5 px/ms even when short, never on an upward one', () => {
        const fling = createSheetDrag()
        fling.down(0, 0)
        fling.move(20, 20)
        fling.move(60, 40)
        expect(fling.up(70, 50, 400)).toBe('close')
        const up = createSheetDrag()
        up.down(0, 0)
        up.move(100, 500)
        up.move(60, 520)
        expect(up.up(40, 530, 400)).toBe('stay')
        const back = createSheetDrag()
        back.down(0, 0)
        back.move(300, 900)
        back.move(300, 940)
        back.move(280, 1010)
        expect(back.up(250, 1020, 400)).toBe('stay')
    })
    it('closes on a fast short flick whose lift lands at the last move position a few ms later', () => {
        const drag = createSheetDrag()
        drag.down(0, 1000)
        drag.move(30, 1020)
        drag.move(60, 1040)
        drag.move(60, 1050)
        expect(drag.up(60, 1055, 400)).toBe('close')
    })
    it('closes on a fast short flick whose lift has the same position and time as the last move', () => {
        const drag = createSheetDrag()
        drag.down(0, 1000)
        drag.move(30, 1020)
        drag.move(60, 1040)
        drag.move(60, 1050)
        expect(drag.up(60, 1050, 400)).toBe('close')
    })
    it('stays after a slow drag, and after a fast drag that rests longer than the window before the lift', () => {
        const slow = createSheetDrag()
        slow.down(0, 0)
        slow.move(50, 100)
        slow.move(60, 200)
        expect(slow.up(60, 210, 400)).toBe('stay')
        const paused = createSheetDrag()
        paused.down(0, 1000)
        paused.move(50, 1005)
        paused.move(100, 1010)
        expect(paused.up(100, 1010 + SHEET_VELOCITY_WINDOW_MS + 40, 400)).toBe('stay')
    })
    it('closes on a fast flick whose moves are sparse and whose last move sits at the lift position', () => {
        const drag = createSheetDrag()
        drag.down(0, 1000)
        drag.move(130, 1050)
        drag.move(262, 1130)
        expect(drag.up(262, 1140, 2000)).toBe('close')
        const batched = createSheetDrag()
        batched.down(0, 1000)
        batched.move(60, 1040)
        batched.move(150, 1080)
        batched.move(262, 1120)
        expect(batched.up(262, 1130, 2000)).toBe('close')
        const settled = createSheetDrag()
        settled.down(0, 1000)
        settled.move(20, 1020)
        settled.move(290, 1100)
        settled.move(300, 1140)
        expect(settled.up(300, 1150, 2000)).toBe('close')
    })
    it('closes on a fast drag of one move whose lift comes 90 ms after the press', () => {
        const drag = createSheetDrag()
        drag.down(0, 1000)
        drag.move(100, 1050)
        expect(drag.up(100, 1090, 2000)).toBe('close')
    })
    it('guard: a fast burst followed by a short gap before the lift at the last move position still closes', () => {
        const drag = createSheetDrag()
        drag.down(0, 1000)
        for (let step = 1; step <= 10; step++) drag.move(step * 40, 1000 + step * 10)
        expect(drag.up(400, 1130, 2000)).toBe('close')
    })
    it('guard: a long slow drag, and a fast drag, followed by a pause longer than the window, do not fling', () => {
        const slow = createSheetDrag()
        slow.down(0, 0)
        for (let step = 1; step <= 10; step++) slow.move(step * 6, step * 100)
        expect(slow.up(60, 1000 + SHEET_VELOCITY_WINDOW_MS + 40, 2000)).toBe('stay')
        const fast = createSheetDrag()
        fast.down(0, 1000)
        fast.move(150, 1050)
        fast.move(300, 1060)
        expect(fast.up(300, 1060 + SHEET_VELOCITY_WINDOW_MS + 40, 2000)).toBe('stay')
    })
    it('stays on a fast upward flick ending at the last move position, even past 30 % of the height', () => {
        const drag = createSheetDrag()
        drag.down(0, 0)
        drag.move(300, 900)
        drag.move(300, 940)
        drag.move(250, 1020)
        drag.move(200, 1040)
        expect(drag.up(200, 1045, 400)).toBe('stay')
    })
    it('keeps a bounded sample buffer without losing the release velocity on a dense stream', () => {
        const drag = createSheetDrag()
        drag.down(0, 0)
        for (let t = 1; t <= 5000; t++) drag.move(t * 0.02, t)
        expect(drag.up(100, 5000, 100000)).toBe('stay')
        const flick = createSheetDrag()
        flick.down(0, 0)
        for (let t = 1; t <= 5000; t++) flick.move(t < 4950 ? 0 : (t - 4949) * 1, t)
        expect(flick.up(51, 5001, 100000)).toBe('close')
    })
    it('treats a press that never passes the slop as a tap, and a cancel as stay', () => {
        const tap = createSheetDrag()
        tap.down(0, 0)
        tap.move(3, 5)
        expect(tap.engaged()).toBe(false)
        expect(tap.up(3, 10, 400)).toBe('stay')
        const cancelled = createSheetDrag()
        cancelled.down(0, 0)
        cancelled.move(300, 10)
        expect(cancelled.engaged()).toBe(true)
        expect(cancelled.cancel()).toBe('stay')
        expect(cancelled.engaged()).toBe(false)
    })
    it('does nothing before a press or after a release', () => {
        const drag = createSheetDrag()
        expect(drag.move(50, 10)).toBe(0)
        expect(drag.up(50, 20, 400)).toBe('stay')
        drag.down(0, 0)
        drag.move(300, 10)
        drag.up(300, 20, 400)
        expect(drag.move(400, 30)).toBe(0)
    })
})

describe('sheet release after a rest (round 3 W2)', () => {
    it('uses the constants of the lag rule', () => {
        expect(SHEET_REST_LAG_MS).toBe(34)
        expect(SHEET_VELOCITY_WINDOW_MS).toBe(80)
    })
    // reproducer
    it('T-SH-REST: a rest on the handle followed by a short fast flick closes, the rest is not averaged into the flick', () => {
        const drag = createSheetDrag()
        drag.down(0, 0)
        for (const [y, t] of [[6, 16.7], [12, 33.4], [18, 50.1], [22, 66.8]]) drag.move(y, t)
        for (const [y, t] of [[30, 233.8], [55, 250.6], [97, 267.3], [140, 283.8], [140, 300.6]]) drag.move(y, t)
        expect(drag.up(140, 309.3, 600)).toBe('close')
    })
    // reproducer
    it('T-SH-LAG40: an anchor 40 ms older than the window start reads over the window and closes', () => {
        const drag = createSheetDrag()
        drag.down(0, 1000)
        for (const [y, t] of [[5, 1010], [10, 1020], [20, 1070], [40, 1100], [60, 1130]]) drag.move(y, t)
        expect(drag.up(60, 1140, 1000)).toBe('close')
    })
    // guard
    it('G-SH-LAG30: an anchor 30 ms older than the window start keeps the true span and stays', () => {
        const drag = createSheetDrag()
        drag.down(0, 1000)
        for (const [y, t] of [[5, 1010], [10, 1020], [20, 1060], [40, 1090], [60, 1120]]) drag.move(y, t)
        expect(drag.up(60, 1130, 1000)).toBe('stay')
    })
    // guard
    it('G-SH-DENSE: a dense 16.7 ms stream reads the true span and stays', () => {
        const drag = createSheetDrag()
        drag.down(0, 0)
        for (let k = 1; k <= 18; k++) drag.move(7.5 * k, 16.7 * k)
        expect(drag.up(140.6, 313, 600)).toBe('stay')
    })
    // guard
    it('G-SHORT: a drag shorter than the window keeps its own span', () => {
        const drag = createSheetDrag()
        drag.down(0, 1000)
        drag.move(10, 1010)
        drag.move(22, 1020)
        drag.move(30, 1030)
        expect(drag.up(30, 1034, 400)).toBe('close')
    })
    // guard (boundary): a lag of exactly the rest lag keeps the true span; one millisecond more reads over the window.
    it('G-SH-LAG-EDGE: a lag of exactly 34 ms keeps the true span and stays, 35 ms reads over the window and closes', () => {
        const release = (liftAt: number) => {
            const drag = createSheetDrag()
            drag.down(0, 0)
            drag.move(40, 100)
            return drag.up(50, liftAt, 1000)
        }
        expect(release(114)).toBe('stay')
        expect(release(115)).toBe('close')
    })
    // guard
    it('G-REST-NOFLICK: a rest longer than the window that lifts at the rest position never flings', () => {
        const drag = createSheetDrag()
        drag.down(0, 0)
        for (const [y, t] of [[20, 20], [60, 40], [100, 60]]) drag.move(y, t)
        expect(drag.up(100, 400, 1000)).toBe('stay')
    })
})
