describe('B9 the checks before the verdict still run every slot', () => {
    interface Injection {
        name: string
        /** Runs after the first, clean slot and before the second. */
        before?: (world: World, db: Database) => Promise<void> | void
        /** Runs inside the second slot's yield. */
        during?: (world: World, db: Database) => void
        options?: StartOptions
        residents?: number
    }

    const injections: Injection[] = [
        {
            name: 'a peer commit',
            async before(world) {
                await peerCommit(world.kit, (peerDb) => { chars(peerDb)[0].name = 'the peer edit' })
            },
        },
        {
            name: 'an unheld resident',
            before(world, db) {
                chars(db).push({ ...clone(chars(db)[0]), chaId: 'brand-new-character', name: 'Brand new' })
                ;(db as unknown as Entry).characterOrder = chars(db).map(slot => slot.chaId)
            },
        },
        {
            name: 'a stub whose name changed',
            before(world, db) {
                const entries = (world.kit.context.previous.objects?.shards ?? []).flatMap(shard => shard.entries)
                const entry = entries.find(candidate => candidate.chaId === idOf(db, 1))
                const stub = stubFromEntry(entry as NonNullable<typeof entry>) as unknown as Entry
                chars(db)[1] = stub
                stub.name = 'Renamed stub'
            },
            residents: 2,
        },
        {
            name: 'a module pass coming due',
            options: { moduleIntervalMs: 5_000 },
        },
        {
            name: 'a pass becoming due during the yield',
            during(world) {
                world.state.due = true
            },
        },
        {
            name: 'a replaced database during the yield',
            during(world, db) {
                world.holder.db = clone(db)
            },
        },
    ]

    /** What the second slot did, with the verdict-or-skip choice normalised away: that choice is the one thing allowed to differ. */
    async function secondSlot(injection: Injection, backstopMs: number): Promise<Array<string | number | null>> {
        const db = clone(buildSmall(injection.residents ?? 1))
        const world = await startWorld(db, { ...injection.options, backstopMs })
        // The first slot is resident 0's: clean, so with a backstop it starts a clock.
        await world.slotAt(1_000)
        await injection.before?.(world, db)
        if (injection.during !== undefined) {
            const during = injection.during
            world.onYield.action = () => during(world, db)
        }
        const slot = await world.slotAt(injection.residents === 2 ? 3_000 : 6_000)
        expect(slot.reads).toBeGreaterThanOrEqual(1)
        expect(world.crashed).toEqual([])
        return [normalized(slot.reason), slot.reads, slot.yields, slot.requests.length]
    }

    test.each(injections)('B9 $name is met by the same slot with and without a fresh clock', async (injection) => {
        const free = await secondSlot(injection, 0)
        const fresh = await secondSlot(injection, 30_000)
        expect(fresh).toEqual(free)
    })

    test('B9 every slot yields once and reads once while the residents are fresh', async () => {
        const world = await startWorld(clone(buildSmall(1)))
        await world.slotAt(1_000)
        for (const offset of [2_000, 3_000, 4_000]) {
            const slot = await world.slotAt(offset)
            expect(slot.reason).toBe('verdictSkipped')
            expect([slot.reads, slot.yields]).toEqual([1, 1])
        }
    })

    test('B9 an unsavable resident that left the database ends the slot before any skip', async () => {
        const build = async (backstopMs: number) => {
            const db = clone(buildSmall(2))
            const world = await startWorld(db, { backstopMs })
            await world.slotAt(1_000)
            const id = idOf(db, 1)
            chars(db)[1].personality = cyclic()
            await world.markedPass([id])
            await until(() => world.unsavableCalls.length > 0, 'the character to be reported unsavable', 4000)
            chars(db).splice(1, 1)
            ;(db as unknown as Entry).characterOrder = chars(db).map(slot => slot.chaId)
            const slot = await world.slotAt(2_000)
            return [slot.reason, slot.requests.length]
        }
        expect(await build(30_000)).toEqual(await build(0))
        expect((await build(30_000))[0]).toBe('unsavableAbsent')
    })
})

describe('B11 an unsavable resident among six', () => {
    test('B11 it is picked at the base\'s turns, retried each time, and its verdict is never called', async () => {
        const db = clone(buildSmall(6))
        const world = await startWorld(db)
        const bad = idOf(db, 3)
        chars(db)[3].personality = cyclic()
        await world.markedPass([bad])
        await until(() => world.unsavableCalls.length > 0, 'the character to be reported unsavable', 4000)
        const judged: Array<number | null> = []
        const planned = world.requests.length
        for (let offset = 1_000; offset <= 12_000; offset += 1_000) {
            judged.push(indexOfId(db, (await world.slotAt(offset)).chaId))
        }
        expect(judged).toEqual(UNSAVABLE_JUDGED_BASE)
        expect(world.verdicts).not.toContain(bad)
        const retries = world.requests.slice(planned).filter(request => request.net?.chaId === bad)
        expect(retries).toHaveLength(2)
    })

    test('E-G4 a resident with a fresh clock that then becomes unsavable is retried at its next turn', async () => {
        const db = clone(buildSmall(3))
        const world = await startWorld(db)
        const ids = [0, 1, 2].map(index => idOf(db, index))
        for (const [index, offset] of [1_000, 2_000, 3_000].entries()) {
            expect((await world.slotAt(offset)).verdicts).toEqual([ids[index]])
        }
        chars(db)[0].personality = cyclic()
        await world.markedPass([ids[0]])
        await until(() => world.unsavableCalls.length > 0, 'the character to be reported unsavable', 4000)
        const planned = world.requests.length
        const slot = await world.slotAt(4_000)
        expect(slot.chaId).toBe(ids[0])
        expect(slot.reason).toBe('verdictUnknown')
        expect(world.requests.slice(planned).map(request => request.net)).toEqual([{ chaId: ids[0], modules: false }])
    })
})

describe('B12 a failing silent pass escalates at the base\'s pace', () => {
    test('B12 the attempts reported by slot, with no other commit landing, equal the base\'s', async () => {
        const db = clone(buildSmall(3))
        const world = await startWorld(db)
        chars(db)[0].personality = 'edited in place, nothing marked'
        world.commitFault.on = true
        const reported: Array<[number, number]> = []
        let seen = 0
        for (let slotNumber = 1; slotNumber <= 14; slotNumber += 1) {
            await world.slotAt(slotNumber * 1_000)
            for (const failure of world.failures.slice(seen)) {
                reported.push([slotNumber, failure.attempts])
            }
            seen = world.failures.length
        }
        expect(reported).toEqual(FAILING_PASS_BASE)
    })
})

describe('B13 hidden to visible', () => {
    test('B13 a resident that failed while hidden verdicts at its next visible turn', async () => {
        const db = clone(buildSmall(1))
        const world = await startWorld(db)
        const id = idOf(db, 0)
        await world.slotAt(1_000)
        world.flags.hidden = true
        chars(db)[0].personality = 'edited while hidden'
        world.commitFault.on = true
        const hidden = await world.slotAt(2_000)
        expect(hidden.verdicts).toEqual([id])
        expect(hidden.reason).toBe('verdictDirty')
        expect(world.failures.length).toBeGreaterThan(0)
        world.flags.hidden = false
        const visible = await world.slotAt(3_000)
        expect(visible.verdicts).toEqual([id])
        expect(visible.reason).toBe('verdictDirty')
    })

    test('B13 a hidden page never skips, even with a fresh clock', async () => {
        const db = clone(buildSmall(1))
        const world = await startWorld(db)
        await world.slotAt(1_000)
        world.flags.hidden = true
        expect((await world.slotAt(2_000)).verdicts).toEqual([idOf(db, 0)])
        expect((await world.slotAt(3_000)).verdicts).toEqual([idOf(db, 0)])
        world.flags.hidden = false
        // The hidden verdicts were clean and set a clock: the visible page may skip again.
        expect((await world.slotAt(4_000)).verdicts).toEqual([])
    })
})

