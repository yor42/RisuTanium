/**
 * CHORE-205 time-only net backstop: the idle net keeps its rotation exactly, and at a resident's
 * turn skips only the verdict when that resident's last clean verdict is younger than the backstop. The loop runs over a
 * real memory backend and committer with a hand-built port whose clock the test sets; a slot is observed through its
 * verdict calls, its plans and the meter's slot record (judged `chaId` and end reason). The measurement switch is on, so
 * the record exists; B1R repeats the core skip with it off, as a release build runs.
 * Labels: B1 to B13 follow the plan. Every sequence marked "base" was generated by running this scenario against the
 * commit before the backstop existed, with the backstop ignored, and holds there unchanged.
 */

type Entry = Record<string, unknown>
type MeterGlobal = { __risuSavePassMeter?: SavePassMeterHandle }
type VerdictMode = 'real' | 'dirty' | 'unknown' | 'throw'

interface Slot {
    reads: number
    yields: number
    verdicts: string[]
    requests: SavePassRequest[]
    reason: NetSlotReason | null
    chaId: string | null
}

interface World {
    kit: Store2Kit
    holder: { db: Database }
    encoder: SaveEncoder
    tracker: toSaveType
    clock: { now: number }
    start: number
    requests: SavePassRequest[]
    verdicts: string[]
    counted: { reads: number, sweeps: number, begun: number, yields: number }
    state: { due: boolean, dirty: boolean }
    flags: { hidden: boolean, sweep: boolean }
    mode: { verdict: VerdictMode }
    commitFault: { on: boolean }
    onYield: { action: (() => void) | null }
    /** Runs once at the top of the loop's next iteration, before it decides whether a slot is due. */
    onSweep: { action: (() => void) | null }
    failures: Array<{ error: unknown, attempts: number }>
    unsavableCalls: Array<{ current: readonly UnsavableCharacter[], newly: readonly UnsavableCharacter[] }>
    crashed: unknown[]
    slotAt(offset: number): Promise<Slot>
    /** A marked pass over `ids` through the loop's own pass path; resolves once the loop has gone on past it. */
    markedPass(ids: string[]): Promise<void>
    stop(): void
}

interface StartOptions {
    /** Defaults to the release constant's value, 30 000. */
    backstopMs?: number
    /** Defaults to a value no test clock reaches, so no slot is a module tick unless the test asks. */
    moduleIntervalMs?: number
    /** Whether the port carries `pageHidden` and `takeNetSweep`; the real port does. */
    realPort?: boolean
}

const worlds: World[] = []

function meterOf(): SavePassMeterHandle {
    const found = (globalThis as MeterGlobal).__risuSavePassMeter
    if (found === undefined) {
        throw new Error('The meter handle is not installed.')
    }
    return found
}

