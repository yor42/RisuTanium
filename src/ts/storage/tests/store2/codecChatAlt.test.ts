// ---- damaged alternatives: dropped, flagged, the conversation intact ----

interface World {
    memory: ReturnType<typeof createMemoryBackend>
    tree: EncodedTree
    manifestKey: string
    entry: ShardEntry
    source: Obj
    altKeys: string[]
}

async function worldWithAlt(count = 24): Promise<World> {
    const alt = records(count, { pad: 'p'.repeat(CHUNK_CAP_BYTES / 8) })
    const source = chatWith(alt)
    const memory = createMemoryBackend()
    const seeded = await seedTree(memory, JSON.parse(JSON.stringify(holder([source]))) as Database, testEnv(createClock(), 4242), fakeLists)
    const entry = entryOf(seeded.tree)
    return { memory, tree: seeded.tree, manifestKey: seeded.manifestKey, entry, source, altKeys: (entry.chats[0].alt ?? []).map(keyOfRef) }
}

function flip(world: World, key: string): void {
    const bytes = world.memory.snapshot().get(key)
    if (bytes === undefined) {
        throw new Error(`No unit ${key}.`)
    }
    const damaged = new Uint8Array(bytes)
    damaged[20] ^= 0xff
    world.memory.poke(key, damaged)
}

async function okRead(world: World) {
    const read = await readTreeBytes(world.memory, world.manifestKey)
    if (read.status !== 'ok') {
        throw new Error(`The tree read ${read.status}.`)
    }
    return read
}

describe('a damaged or missing alternatives unit is flagged and dropped; the conversation stays whole (new-rule guard)', () => {
    test.each(['flip', 'missing'] as const)('a %s alternatives unit is flagged as part alt with its chat, and only its records are lost', async (how) => {
        const world = await worldWithAlt()
        expect(world.altKeys.length).toBeGreaterThan(2)
        const victim = world.altKeys[1]
        if (how === 'flip') {
            flip(world, victim)
        } else {
            world.memory.poke(victim, null)
        }
        const read = await okRead(world)
        expect(read.flagged).toHaveLength(1)
        expect(read.flagged[0]).toMatchObject({ kind: 'chat', chatId: 'chat-alt-1', part: 'alt', key: victim, why: how === 'flip' ? 'damaged' : 'missing' })
        expect(read.tree.source.get(victim)).toBeUndefined()
        const fallback = createLeafFallback(read.flagged, () => 1)
        const assembled = assembleDatabase(read.tree.manifest, read.tree.source, { character: fallback.character })
        const chatBack = (assembled.characters[0] as unknown as { chats: Obj[] }).chats[0]
        expect(chatBack.message).toEqual(world.source.message)
        const kept = world.altKeys.flatMap((key, k) => (k === 1 ? [] : (bodyOf(unitByKey(world, key)) as unknown as ChatAltUnit).recs))
        expect(chatBack.alt).toEqual(kept)
        expect(fallback.items()[0]).toMatchObject({ part: 'alt', name: 'Holder' })
    })

    test('a unit whose body count differs from its Ref is flagged as damaged alt, not thrown', async () => {
        const world = await worldWithAlt()
        const shardRef = world.tree.manifest.shards.find(ref => ((bodyOf(world.tree.units.find(unit => unit.key === keyOfRef(ref))!) as unknown as Shard).entries.length > 0))!
        const shardKey = keyOfRef(shardRef)
        const body = structuredClone(bodyOf(world.tree.units.find(unit => unit.key === shardKey)!)) as unknown as Shard
        const target = body.entries[0].chats[0].alt![0]
        target[3] += 1
        const rewritten = encodeUnit(UNIT_TYPE.shard, body)
        const manifest = structuredClone(world.tree.manifest)
        manifest.shards = manifest.shards.map(ref => keyOfRef(ref) === shardKey ? refOfFrame(shardKey, rewritten) : ref)
        world.memory.poke(shardKey, rewritten)
        world.memory.poke(world.manifestKey, encodeUnit(UNIT_TYPE.manifest, manifest))
        const read = await okRead(world)
        expect(read.flagged).toHaveLength(1)
        expect(read.flagged[0]).toMatchObject({ kind: 'chat', part: 'alt', why: 'damaged', key: keyOfRef(target) })
        const fallback = createLeafFallback(read.flagged, () => 1)
        expect(() => assembleDatabase(read.tree.manifest, read.tree.source, { character: fallback.character })).not.toThrow()
    })

    test('an entity read opens with its main conversation and names the dropped units; a damaged chunk still refuses', async () => {
        const world = await worldWithAlt()
        flip(world, world.altKeys[0])
        const read = await readEntityBytes(world.memory, world.entry)
        expect(read.status).toBe('ok')
        if (read.status === 'ok') {
            expect(read.droppedAlt).toHaveLength(1)
            expect(read.droppedAlt[0]).toMatchObject({ part: 'alt', key: world.altKeys[0] })
            expect(read.source.get(world.altKeys[0])).toBeUndefined()
        }
        flip(world, keyOfRef(world.entry.chats[0].chunks[0]))
        const refused = await readEntityBytes(world.memory, world.entry)
        expect(refused.status).toBe('damaged')
    })

    test('an entity read that drops alternatives is refused as moved when the commit key no longer names its tree', async () => {
        const world = await worldWithAlt()
        flip(world, world.altKeys[0])
        const moved = await readEntityBytes(world.memory, world.entry, { manifestKey: 'm-0000000000000000000000000x' })
        expect(moved.status).toBe('moved')
        const named = await readEntityBytes(world.memory, world.entry, { manifestKey: world.manifestKey })
        expect(named.status).toBe('ok')
    })
})

function unitByKey(world: World, key: string) {
    const unit = world.tree.units.find(candidate => candidate.key === key)
    if (unit === undefined) {
        throw new Error(`No unit ${key}.`)
    }
    return unit
}
