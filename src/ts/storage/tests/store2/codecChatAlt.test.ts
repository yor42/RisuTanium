        expect(absent.manifestKey).toBe(empty.manifestKey)
        expect(empty.manifest.req).toEqual([])
        expect(Object.hasOwn(entryOf(empty).chats[0], 'alt')).toBe(false)
        expect(altIdentities(empty)).toEqual([])
        const core = bodyOf(unitOf(empty, `chat:${entryOf(empty).u}:chat-alt-1:core`))
        expect(Object.hasOwn(core.f as JsonObject, 'alt')).toBe(false)
