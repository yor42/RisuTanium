/**
 * Chat alternatives in the store2 format: the `alt` list of a chat is stored as type 25 units (`chatAlt`), the `chat-alt`
 * token marks a store that has them, and a store without any encodes exactly as it did before they existed. Labels:
 * compatibility guard (passes on the base too), regression reproducer (fails on the base), new-rule guard.
 */

// ---- fixtures ----

const FIRST_TIME = 1_700_000_100_000

/** An alternative record; `extra` keys are the open part of the record. */
function altRecord(n: number, extra: Obj = {}): Obj {
    return {
        m: { role: 'char', data: `alternative ${n}`, time: FIRST_TIME + n, chatId: `alt-${n}` },
        p: n === 0 ? null : `msg-${n - 1}`,
        a: n + 1,
        ...extra,
    }
}

function records(count: number, extra: Obj = {}): Obj[] {
    return Array.from({ length: count }, (_, n) => altRecord(n, extra))
}

/** A chat with three stamped messages and, when given, the `alt` value as it is (any shape, so malformed values can be tested). */
function chatWith(alt: unknown): Obj {
    const rng = mulberry32(31)
    const pool = prosePool(rng, 6, 20, 60)
    const out = chat(rng, 0, Array.from({ length: 3 }, (_, i) => ({ ...message(rng, pool, i, 40), chatId: `msg-${i}` })))
    out.id = 'chat-alt-1'
    if (alt !== undefined) {
        out.alt = alt
    }
    return out
}

function holder(chats: Obj[]): Database {
    const rng = mulberry32(5)
    return dbWithCharacters([sparseCharacter(rng, prosePool(rng, 5, 10, 40), 'holder', 'Holder', chats, [])])
}

function entryOf(tree: EncodedTree, ...earlier: EncodedTree[]): ShardEntry {
    const entries = tree.units.filter(unit => unit.type === UNIT_TYPE.shard).flatMap(unit => (bodyIn(unit, ...earlier) as unknown as Shard).entries)
    expect(entries).toHaveLength(1)
    return entries[0]
}

function altIdentities(tree: EncodedTree): string[] {
    return identitiesWhere(tree, 'chat:').filter(identity => identity.includes(':alt:'))
}

function assembledChat(tree: EncodedTree): Obj {
    const assembled = assembleDatabase(tree.manifest, unitMapSource(tree.units))
    return (assembled.characters[0] as unknown as { chats: Obj[] }).chats[0]
}

function digestOf(db: Database): string {
    const tree = encodeWith(db)
    const units = tree.units.map(unit => [unit.identity, unit.key, unit.reused ? 'reused' : createHash('sha256').update(bytesOf(unit)).digest('hex')])
    return createHash('sha256').update(JSON.stringify([tree.manifestKey, tree.manifest.req, units])).digest('hex')
}

