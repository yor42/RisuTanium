describe('alternatives are stored as type 25 units', () => {
    test('the records are in a unit of their own, the core and chunks hold none, and the chat round-trips deep-equal (regression reproducer)', () => {
        const alt = [...records(2), altRecord(2, { x: { keep: [1, 'two'], deeper: { n: null } }, mem: { supaMemoryData: 'parked' } })]
        const source = chatWith(alt)
        const tree = encodeWith(holder([source]))
        const entry = entryOf(tree)
        const ids = altIdentities(tree)
        expect(ids).toHaveLength(1)
        const unit = unitOf(tree, ids[0])
        expect(unit.type).toBe(UNIT_TYPE.chatAlt)
        expect(bodyOf(unit)).toEqual({ v: 1, recs: alt })
        expect(entry.chats[0].alt).toEqual([[unit.ref[0], unit.ref[1], unit.ref[2], 3]])
        const core = bodyOf(unitOf(tree, `chat:${entry.u}:chat-alt-1:core`))
        expect(Object.hasOwn(core.f as JsonObject, 'alt')).toBe(false)
        const chunk = bodyOf(unitOf(tree, `chat:${entry.u}:chat-alt-1:chunk:0`))
        expect(JSON.stringify(chunk)).not.toContain('alternative')
        expect(assembledChat(tree)).toEqual(source)
    })

    test('a record with keys this build does not know keeps them through encode and assemble (open record)', () => {
        const alt = [altRecord(0, { future: { nested: [true, null, 'x'] }, mem: { scriptstate: { a: 1 } } })]
        const tree = encodeWith(holder([chatWith(alt)]))
        expect(bodyOf(unitOf(tree, altIdentities(tree)[0])).recs).toEqual(alt)
        expect(assembledChat(tree).alt).toEqual(alt)
    })

    test('the manifest and the commit key carry the chat-alt token when a chat has alternatives (regression reproducer)', async () => {
        const db = holder([chatWith(records(2))])
        const memory = createMemoryBackend()
        const seeded = await seedTree(memory, JSON.parse(JSON.stringify(db)) as Database, testEnv(createClock(), 7), fakeLists)
        expect(seeded.tree.manifest.req).toEqual([REQ_CHAT_ALT])
        const stored = classifyCommitRead({ bytes: (await memory.readCommit()).bytes })
        expect(stored.status).toBe('parsed')
        if (stored.status === 'parsed') {
            expect(stored.value.req).toEqual(['chat-alt'])
        }
    })

    test('the token is never lowered: a re-encode over the previous keeps it, and a commit key over a manifest without it keeps it', () => {
        const first = encodeWith(holder([chatWith(records(2))]))
        expect(first.manifest.req).toEqual(['chat-alt'])
        const cleared = holder([chatWith(undefined)])
        const second = encodeWith(cleared, { previous: previousFrom(first), seq: 2, env: seededEnv(2) })
        expect(second.manifest.req).toEqual(['chat-alt'])
        expect(Object.hasOwn(entryOf(second, first).chats[0], 'alt')).toBe(false)
        expect(altIdentities(second)).toEqual([])
        const fresh = encodeWith(cleared)
        expect(fresh.manifest.req).toEqual([])
        const base = firstCommitKey({ current: { key: first.manifestKey, at: 1 }, staging: null, manifests: [first.manifest] })
        expect(base.req).toEqual(['chat-alt'])
        expect(nextCommitKey(base, { manifests: [fresh.manifest] }).req).toEqual(['chat-alt'])
    })

    test('a manifest that needs a token this build does not know is too-new, and chat-alt is known (compatibility guard)', () => {
        const manifest = structuredClone(encodeWith(holder([chatWith(records(1))])).manifest) as Manifest
        expect(parseManifest(manifest as unknown as JsonObject).status).toBe('ok')
        manifest.req = ['chat-alt', 'chat-alt-v2']
        expect(parseManifest(manifest as unknown as JsonObject).status).toBe('too-new')
    })

    test('a value that is not a list of alternative records stays a core field, sets no token and never throws (new-rule guard)', () => {
        const malformed: unknown[] = ['text', 7, { not: 'a list' }, [{ m: 'x', p: null, a: 1 }], [{ m: {}, p: 3, a: 1 }], [{ m: {}, p: null, a: '1' }], [{ m: {}, p: null }], [1]]
        for (const value of malformed) {
            const source = chatWith(value)
            const tree = encodeWith(holder([source]))
            expect(tree.manifest.req, JSON.stringify(value)).toEqual([])
            expect(altIdentities(tree), JSON.stringify(value)).toEqual([])
            const core = bodyOf(unitOf(tree, `chat:${entryOf(tree).u}:chat-alt-1:core`))
            expect((core.f as JsonObject).alt, JSON.stringify(value)).toEqual(value)
            expect(assembledChat(tree).alt, JSON.stringify(value)).toEqual(value)
        }
    })

    test('isWellFormedAlt and chatCoreFields agree on what is a list of records', () => {
        expect(isWellFormedAlt([])).toBe(true)
        expect(isWellFormedAlt(records(2) as never)).toBe(true)
        expect(isWellFormedAlt(undefined)).toBe(false)
        expect(isWellFormedAlt('x')).toBe(false)
        expect(isWellFormedAlt([{ m: {}, p: null, a: Number.NaN }] as never)).toBe(false)
        expect(Object.hasOwn(chatCoreFields({ alt: [], name: 'c' }), 'alt')).toBe(false)
        expect(Object.hasOwn(chatCoreFields({ alt: records(1) as never, name: 'c' }), 'alt')).toBe(false)
        expect(chatCoreFields({ alt: 'x', name: 'c' }).alt).toBe('x')
    })
})

describe('alternatives are sealed in order, so an append or a removal at the end rewrites one unit (new-rule guard)', () => {
    const padded = (count: number) => records(count, { pad: 'p'.repeat(CHUNK_CAP_BYTES / 8) })

    test('a long list is several units, each within the cap, and round-trips in order', () => {
        const alt = padded(30)
        const tree = encodeWith(holder([chatWith(alt)]))
        const ids = altIdentities(tree)
        expect(ids.length).toBeGreaterThan(2)
        ids.forEach((id, k) => expect(id.endsWith(`:alt:${k}`)).toBe(true))
        expect(entryOf(tree).chats[0].alt?.reduce((sum, ref) => sum + ref[3], 0)).toBe(30)
        for (const id of ids) {
            expect(bytesOf(unitOf(tree, id)).length).toBeLessThanOrEqual(CHUNK_CAP_BYTES + 1024)
        }
        expect(assembledChat(tree).alt).toEqual(alt)
    })

    test('appending one record changes only the last alternatives unit or adds one; removing the last record changes only one', () => {
        const first = encodeWith(holder([chatWith(padded(24))]))
        const ids = altIdentities(first)
        const keyOf = (tree: EncodedTree, id: string): string | undefined => tree.units.find(unit => unit.identity === id)?.key
        const appended = encodeWith(holder([chatWith(padded(25))]), { previous: previousFrom(first), seq: 2, env: seededEnv(2) })
        const removed = encodeWith(holder([chatWith(padded(23))]), { previous: previousFrom(first), seq: 2, env: seededEnv(2) })
        for (const other of [appended, removed]) {
            ids.slice(0, -1).forEach(id => expect(keyOf(other, id), id).toBe(keyOf(first, id)))
        }
        expect(altIdentities(appended).length - ids.length).toBeGreaterThanOrEqual(0)
        expect(altIdentities(appended).length - ids.length).toBeLessThanOrEqual(1)
    })
})

