interface LiveMessage { role: 'user' | 'char', data: string }

const view = $state({ gone: false })
const mounted: { target: HTMLElement, instance: Record<string, unknown> }[] = []

function mountList() {
    view.gone = false
    selectedCharID.set(0)
    DBState.db = baseDb() as never
    const messages: LiveMessage[] = [{ role: 'user', data: 'hi' }, { role: 'char', data: 'hello' }]
    DBState.db.characters = [makeCharacter('ch0', [makeChat('c0', { message: messages })], { image: '' })] as never
    const target = document.createElement('div')
    document.body.appendChild(target)
    const instance = mount(Chats, {
        target,
        props: {
            // Fixed: the screen's messages stay as they were until it re-renders without the list.
            messages: messages as never,
            get currentCharacter() { return (view.gone ? undefined : DBState.db.characters[0]) as never },
            onReroll: () => {},
            unReroll: () => {},
            currentUsername: 'User',
            userIcon: '',
            loadPages: 100,
        },
    })
    mounted.push({ target, instance })
    flushSync()
}

beforeEach(() => {
    rec.reads = 0
    rec.errors.length = 0
})

afterEach(() => {
    for (const { target, instance } of mounted.splice(0)) {
        unmount(instance)
        target.remove()
    }
})

describe('the classic chat list after its character is gone', () => {
    test('R: the rows re-read the tree view without an error and the list effect does not throw', async () => {
        mountList()
        await tick()
        flushSync()
        expect(rec.reads, 'the stub rows read the tree view once mounted').toBeGreaterThan(0)
        const readsBefore = rec.reads

        view.gone = true
        expect(() => flushSync()).not.toThrow()
        await tick()

        expect(rec.errors).toEqual([])
        expect(rec.reads, 'the rows re-read the tree view after the character went').toBeGreaterThan(readsBefore)
    })
})
