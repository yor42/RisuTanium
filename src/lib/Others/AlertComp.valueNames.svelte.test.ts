import { alertStore, DBState } from '../../ts/stores.svelte'
import { language } from 'src/lang'
import { fieldNameProblems, unnamedControls } from 'src/lib/a11yNames.test-helpers'
import AlertComp from './AlertComp.svelte'

const mountedTargets: HTMLElement[] = []
const mountedInstances: unknown[] = []

function mountAlertComp(): HTMLElement {
    const target = document.createElement('div')
    document.body.appendChild(target)
    mountedTargets.push(target)
    mountedInstances.push(mount(AlertComp, { target, props: {} }))
    return target
}

afterEach(async () => {
    const instances = mountedInstances.splice(0)
    for (const instance of instances) {
        await unmount(instance as never).catch(() => {})
    }
    mountedTargets.splice(0).forEach((t) => t.remove())
    document.body.replaceChildren()
    alertStore.set({ type: 'none', msg: '' } as never)
})

describe('AlertComp value control names', () => {
    test('the character export format select is named by its visible label', () => {
        DBState.db = {
            characters: [{ type: 'character', chaId: 'c0', ccAssets: [], additionalAssets: [], emotionImages: [], image: '' }],
        } as unknown as Database
        alertStore.set({ type: 'cardexport', msg: '', submsg: '' } as never)
        const target = mountAlertComp()
        flushSync()
        const v3 = Array.from(target.querySelectorAll('button')).find((b) => b.textContent?.trim() === 'Character Card V3')
        if (!v3) expect.fail('no Character Card V3 button')
        v3.click()
        flushSync()
        expect(fieldNameProblems(target, [{ name: language.format }])).toEqual([])
        expect(unnamedControls(target, { fields: true, values: true })).toEqual([])
    })
})
