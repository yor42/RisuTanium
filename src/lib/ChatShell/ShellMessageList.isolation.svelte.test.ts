import ShellMessageList from './ShellMessageList.svelte'

let app: ReturnType<typeof ShellMessageList> | undefined
let target: HTMLElement
const character = $state({ chaId: 'c', type: 'character', name: 'Ari', image: '', chatPage: 0,
    chats: [{ id: 'room', message: [] as Message[] }] }) as Character

afterEach(async () => {
    if (app) await unmount(app)
    app = undefined
    target?.remove()
    character.chats[0].message = []
    character.chats[0].isStreaming = false
    parsed.texts = []
})

describe('ShellMessageList stream-tick isolation', () => {
    test('a stream chunk re-parses no completed row', async () => {
        character.chats[0].message = [
            { chatId: 'one', role: 'char', data: 'completed one' },
            { chatId: 'two', role: 'user', data: 'completed two' },
            { chatId: 'stream', role: 'char', data: 'streaming' },
        ]
        character.chats[0].isStreaming = true
        target = document.createElement('div')
        const host = document.createElement('main')
        target.appendChild(host)
        document.body.appendChild(target)
        app = mount(ShellMessageList, { target: host, props: { character, host } })
        flushSync()
        await tick()
        parsed.texts = []
        for (let chunk = 0; chunk < 5; chunk++) {
            character.chats[0].message[2].data += ` chunk${chunk}`
            flushSync()
            await tick()
        }
        expect(parsed.texts.filter((text) => text.startsWith('completed'))).toEqual([])
    })
})
